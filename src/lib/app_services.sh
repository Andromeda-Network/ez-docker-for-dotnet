# An app is one or more services (containers) deployed together: SERVICES in app.env, default
# "web". Each service is configured by variables named after it (SVC = the name upper-cased,
# '-' as '_'), all optional:
#
#   <SVC>_PROJECT     the .csproj to publish (web: PROJECT)
#   <SVC>_CONTEXT     build context, relative to the repository root (default: the root)
#   <SVC>_DOCKERFILE  Dockerfile, relative to the context (default: ez's dotnet.Dockerfile)
#   <SVC>_IMAGE       image mode: the image name without tag (default: APP_IMAGE's name,
#                     plus -<service> for services other than web)
#   <SVC>_PORT        host port to publish the service's 8080 on (web: APP_PORT)
#   <SVC>_HEALTH      how ez decides the service is up after a deploy:
#                       empty   the image's own HEALTHCHECK (dotnet.Dockerfile: /healthz), else running
#                       /path   ez requests http://<container>:8080/path from the host (images without curl)
#                       none    running is enough (workers without HTTP)
#
# ez writes the compose file for an environment from these (env/generated/compose.<env>.yml);
# apps/<app>/compose.override.yml, when present, is applied on top for anything else
# (extra volumes, environment, depends_on).

app_services() { echo "${SERVICES:-web}"; }

svc_key() { local s="${1^^}"; echo "${s//-/_}"; }

svc_get() {
  local name
  name="$(svc_key "$1")_$2"
  echo "${!name:-}"
}

svc_project() {
  if [[ "$1" == "web" ]]; then echo "${WEB_PROJECT:-$PROJECT}"; else svc_get "$1" PROJECT; fi
}

svc_port() {
  if [[ "$1" == "web" ]]; then echo "${WEB_PORT:-$APP_PORT}"; else svc_get "$1" PORT; fi
}

svc_container() {
  if [[ "$1" == "web" ]]; then echo "${args[APP_NAME]}_${args[APP_ENV]}"; else echo "${args[APP_NAME]}_${args[APP_ENV]}_$1"; fi
}

# Build mode: the image built on this host. Docker image names are lowercase.
svc_build_image() {
  local app="${args[APP_NAME],,}"
  if [[ "$1" == "web" ]]; then echo "$app:${args[APP_ENV]}"; else echo "$app-$1:${args[APP_ENV]}"; fi
}

# Image mode: the image name (no tag) a service is pulled from.
svc_registry_name() {
  local own base
  own=$(svc_get "$1" IMAGE)
  if [[ -n "$own" ]]; then echo "$own"; return; fi
  base=$(image_name "$APP_IMAGE")
  if [[ "$1" == "web" ]]; then echo "$base"; else echo "$base-$1"; fi
}

validate_services() {
  local svc
  for svc in $(app_services); do
    if [[ ! "$svc" =~ ^[a-z][a-z0-9-]{0,30}$ ]]; then
      log_error "Invalid service name '$svc' in SERVICES: lowercase letters, digits and '-'."
      exit 1
    fi
    if [[ -z "$(svc_project "$svc")" && -z "$(svc_get "$svc" DOCKERFILE)" ]]; then
      log_error "Service '$svc' has no project: set $(svc_key "$svc")_PROJECT (or $(svc_key "$svc")_DOCKERFILE)."
      exit 1
    fi
  done
}

# YAML double-quoted scalar.
yq() { local v="${1//\\/\\\\}"; printf '"%s"' "${v//\"/\\\"}"; }

# generate_compose <file> <image tag>: the compose file for this environment. Paths are absolute,
# so the file reads the same from anywhere.
generate_compose() {
  local file=$1 tag=$2
  local env_name="${args[APP_ENV]}" root svc project port health context dockerfile src image key
  root="$(pwd)/$app_dir"
  src="$root/src-$env_name"

  {
    echo "# Generated by ez for ${args[APP_NAME]} ($env_name) from env/app.env; do not edit."
    echo "# Customize with $app_dir/compose.override.yml."
    echo "services:"
    for svc in $(app_services); do
      project=$(svc_project "$svc")
      port=$(svc_port "$svc")
      health=$(svc_get "$svc" HEALTH)
      context="$src/$(svc_get "$svc" CONTEXT)"
      context="${context%/}"
      dockerfile=$(svc_get "$svc" DOCKERFILE)
      if [[ -n "$dockerfile" ]]; then dockerfile="$context/$dockerfile"; else dockerfile="$root/dotnet.Dockerfile"; fi

      echo "  $svc:"
      echo "    container_name: $(yq "$(svc_container "$svc")")"
      if [[ "$env_name" == "dev" ]]; then
        # dev: dotnet watch on the live checkout, nothing built.
        echo "    image: $(yq "mcr.microsoft.com/dotnet/sdk:${DOTNET_VERSION:-10.0}")"
        echo "    working_dir: /src"
        echo "    user: $(yq "${OWNER_USER_ID}:${OWNER_GROUP_ID}")"
        echo "    command: [ \"dotnet\", \"watch\", \"run\", \"--project\", $(yq "$project"), \"--no-launch-profile\" ]"
      elif [[ "$DEPLOY_MODE" == "image" ]]; then
        echo "    image: $(yq "$(svc_registry_name "$svc"):$tag")"
      else
        echo "    image: $(yq "$(svc_build_image "$svc")")"
        echo "    build:"
        echo "      context: $(yq "$context")"
        echo "      dockerfile: $(yq "$dockerfile")"
        echo "      args:"
        echo "        PROJECT: $(yq "$project")"
        echo "        DOTNET_VERSION: $(yq "${DOTNET_VERSION:-10.0}")"
      fi
      echo "    restart: unless-stopped"
      echo "    env_file: [ $(yq "$root/env/generated/$env_name.env") ]"
      echo "    environment:"
      echo "      ASPNETCORE_ENVIRONMENT: $(yq "$ASPNETCORE_ENVIRONMENT")"
      echo "      EZ_SERVICE: $(yq "$svc")"
      if [[ "$env_name" == "dev" ]]; then
        echo "      ASPNETCORE_URLS: \"http://0.0.0.0:8080\""
        echo "      DOTNET_CLI_HOME: \"/tmp\""
        echo "      NUGET_PACKAGES: \"/tmp/nuget\""
        echo "      DOTNET_USE_POLLING_FILE_WATCHER: \"1\""
        echo "    volumes: [ $(yq "$src:/src") ]"
      else
        echo "    volumes: [ $(yq "$root/storage-$env_name:/app/data") ]"
      fi
      if [[ -n "$port" ]]; then
        echo "    ports: [ $(yq "$port:8080") ]"
      fi
      if [[ -n "$health" ]]; then
        # ez checks these itself (wait_for_service): the image's /healthz check would disagree.
        echo "    healthcheck: { disable: true }"
      fi
      echo "    logging: { driver: json-file, options: { max-size: \"20m\", max-file: \"5\" } }"
      echo "    networks: [ shared ]"
    done

    # The EF Core migrations bundle, from the web service's build (or image), run once per deploy.
    echo "  migrate:"
    echo "    profiles: [ migrate ]"
    echo "    restart: \"no\""
    echo "    env_file: [ $(yq "$root/env/generated/$env_name.env") ]"
    echo "    environment: { ASPNETCORE_ENVIRONMENT: $(yq "$ASPNETCORE_ENVIRONMENT") }"
    echo "    networks: [ shared ]"
    if [[ "$DEPLOY_MODE" == "image" && "$env_name" != "dev" ]]; then
      echo "    image: $(yq "$(image_name "$APP_IMAGE")-migrations:$tag")"
    else
      key=web; [[ " $(app_services) " == *" web "* ]] || key=$(app_services | awk '{print $1}')
      context="$src/$(svc_get "$key" CONTEXT)"; context="${context%/}"
      echo "    image: $(yq "${args[APP_NAME],,}-migrations:$env_name")"
      echo "    build:"
      echo "      context: $(yq "$context")"
      echo "      dockerfile: $(yq "$root/dotnet.Dockerfile")"
      echo "      target: migrations"
      echo "      args:"
      echo "        PROJECT: $(yq "$(svc_project "$key")")"
      echo "        EF_PROJECT: $(yq "${EF_PROJECT:-}")"
      echo "        DOTNET_VERSION: $(yq "${DOTNET_VERSION:-10.0}")"
    fi

    echo "networks:"
    echo "  shared:"
    echo "    external: true"
    echo "    name: $(yq "$SHARED_NETWORK_NAME")"
  } > "$file"
}

# wait_for_service <service>: is it up, the way its <SVC>_HEALTH says?
wait_for_service() {
  local svc=$1 health container
  health=$(svc_get "$svc" HEALTH)
  container=$(svc_container "$svc")
  case "$health" in
    "")    wait_for_healthy "$container" ;;
    none)  wait_for_running "$container" ;;
    /*)    wait_for_http "$container" "$health" ;;
    *)     log_error "$(svc_key "$svc")_HEALTH must be empty, none or a /path (got '$health')."; return 1 ;;
  esac
}

wait_for_all_services() {
  local svc failed=0
  for svc in $(app_services); do
    if ! wait_for_service "$svc"; then
      log_error "$(svc_container "$svc") is not up."
      docker logs --tail 40 "$(svc_container "$svc")" 2>&1 || true
      failed=1
    fi
  done
  return $failed
}
